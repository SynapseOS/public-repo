#!/bin/sh
# uname-linux.sh: сообщить Linux внутри совместимой песочницы Steam
# Автор: Елчинян Арен Артурович, 2026
# Архитектура: x86_64, ABI: Linux
# Описание: Steam проверяет имя ОС до запуска своего клиента
# Подсистема: совместимость Flatpak
# Первое изменение: 29.10.2026
# Последнее изменение: 29.10.2026
# Доступ: общедоступный

case "$*" in
    "" | "-s" | "--kernel-name")
        printf 'Linux\n'
        ;;
    *)
        exec /usr/bin/uname "$@"
        ;;
esac
